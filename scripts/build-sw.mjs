#!/usr/bin/env node
// After `next build`: writes out/sw.js (offline app shell) and out/offline.json (everything the
// "Download lessons" button stores: pages + recorded audio). Cache names carry a hash of the
// file list, so a new deploy replaces the old shell.
import { createHash } from "node:crypto";
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(fileURLToPath(new URL(".", import.meta.url)), "..");
const OUT = join(ROOT, "out");
const BASE = process.env.NEXT_PUBLIC_BASE_PATH ?? "/b2";

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const files = walk(OUT).map((p) => relative(OUT, p).split(sep).join("/"));
const url = (f) => `${BASE}/${f}`.replace(/\/index\.html$/, "/");
const pages = files.filter((f) => f.endsWith(".html") && !f.startsWith("404") && !f.startsWith("_not-found")).map(url);
const statics = files.filter((f) => f.startsWith("_next/static/") && !f.endsWith(".map")).map(url);
const extras = files.filter((f) => /^(icon[^/]*|apple-icon[^/]*|manifest\.webmanifest)$/.test(f)).map(url);
const audio = files.filter((f) => f.startsWith("audio/") && f.endsWith(".m4a")).map(url);

const version = createHash("sha1").update(JSON.stringify([pages, statics, extras])).digest("hex").slice(0, 10);
const shell = [...new Set([`${BASE}/`, ...pages, ...statics, ...extras])];

writeFileSync(join(OUT, "offline.json"), JSON.stringify({ version, pages, audio }));

const sw = `// Generated by scripts/build-sw.mjs — do not edit.
const VERSION = ${JSON.stringify(version)};
const BASE = ${JSON.stringify(BASE)};
const SHELL_CACHE = "b2-shell-" + VERSION;
const AUDIO_CACHE = "b2-audio";
const SHELL = ${JSON.stringify(shell)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(SHELL_CACHE).then(async (cache) => {
      // Small batches so one slow file does not fail the whole install.
      for (let i = 0; i < SHELL.length; i += 8) {
        await Promise.all(SHELL.slice(i, i + 8).map((u) => cache.add(new Request(u, { cache: "reload" })).catch(() => undefined)));
      }
    }).then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("b2-shell-") && k !== SHELL_CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

function timeout(ms) {
  return new Promise((_, reject) => setTimeout(() => reject(new Error("timeout")), ms));
}

async function fromCache(request) {
  const hit = await caches.match(request, { ignoreSearch: true });
  if (hit) return hit;
  const url = new URL(request.url);
  if (!url.pathname.endsWith("/")) {
    const withSlash = await caches.match(url.pathname + "/", { ignoreSearch: true });
    if (withSlash) return withSlash;
  }
  return undefined;
}

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin || !url.pathname.startsWith(BASE + "/")) return;

  if (url.pathname.startsWith(BASE + "/_next/static/")) {
    event.respondWith(
      fromCache(request).then((hit) => hit || fetch(request).then((res) => {
        if (res.ok) caches.open(SHELL_CACHE).then((c) => c.put(request, res.clone()));
        return res;
      })),
    );
    return;
  }

  if (url.pathname.startsWith(BASE + "/audio/")) {
    event.respondWith(
      caches.open(AUDIO_CACHE).then(async (cache) => {
        const hit = await cache.match(request, { ignoreSearch: true });
        if (hit) return hit;
        const res = await fetch(request);
        if (res.ok) cache.put(request, res.clone());
        return res;
      }),
    );
    return;
  }

  if (request.mode === "navigate") {
    event.respondWith(
      Promise.race([fetch(request), timeout(4000)])
        .then((res) => {
          if (res.ok) caches.open(SHELL_CACHE).then((c) => c.put(request, res.clone()));
          return res;
        })
        .catch(async () => (await fromCache(request)) || (await caches.match(BASE + "/")) || Response.error()),
    );
    return;
  }

  event.respondWith(
    fromCache(request).then((hit) => {
      const network = fetch(request)
        .then((res) => {
          if (res.ok) caches.open(SHELL_CACHE).then((c) => c.put(request, res.clone()));
          return res;
        })
        .catch(() => hit);
      return hit || network;
    }),
  );
});
`;
writeFileSync(join(OUT, "sw.js"), sw);
console.log(`sw.js ${version}: ${shell.length} shell files, ${audio.length} audio files in offline.json`);
